def neg(x): return x[1:] if x.startswith("¬") else "¬" + x
def check_kb(rules):
    contra, redund = [], []
    for (a, ca, ka, _), (b, cb, kb, _) in itertools.combinations(rules, 2):
        if ca == cb and ka == neg(kb): contra.append((a, b, sorted(ca), ka, kb))
        if ka == kb and ca < cb: redund.append((b, a, "умови ширші, висновок той самий"))
        if ka == kb and cb < ca: redund.append((a, b, "умови ширші, висновок той самий"))
    return contra, redund
