# %% [Р4.2] Прямий ланцюг виведення з протоколом і поясненням «чому»
def forward_chain(facts, rules, verbose=True):
    facts = set(facts); why = {f: ("факт", None) for f in facts}; log = []; step = 0
    changed = True
    while changed:
        changed = False
        for rid, cond, concl, _ in rules:
            if cond <= facts and concl not in facts:
                step += 1; facts.add(concl); why[concl] = (rid, sorted(cond)); changed = True
                log.append((step, rid, " І ".join(sorted(cond)), concl))
    if verbose:
        for s, rid, c, k in log: print(f"  крок {s}: спрацювало {rid}: {c} → {k}")
    return facts, why, log

def explain(goal, why, indent=0):
    src, cond = why[goal]
    if src == "факт":
        return [" " * indent + f"• {goal} — вхідний факт"]
    out = [" " * indent + f"• {goal} — за правилом {src}, бо:"]
    for c in cond: out += explain(c, why, indent + 4)
    return out

def diagnoses(facts):
    diag = set(IS_A) & facts
    return sorted(diag), sorted(f for f in facts if f.startswith("дія:"))

