r.h1("Теоретичні відомості")
r.p("**Властивісний граф** (labeled property graph, LPG) — модель даних, у якій **вузли** мають "
    "одну або кілька **міток** (labels, наприклад :Component), **ребра** (relationships) мають "
    "рівно один **тип** (:HAS_PART) і напрямок, а і вузли, і ребра зберігають довільні пари "
    "ключ — значення (**властивості**). На відміну від RDF, де будь-який факт — трійка "
    "суб'єкт — предикат — об'єкт, а атрибути ребер потребують реїфікації, LPG дозволяє прямо "
    "записати, наприклад, вагу чи дату зв'язку. Найпоширеніша СКБД цього типу — **Neo4j** "
    "(native graph storage, index-free adjacency: кожен вузол зберігає вказівники на свої ребра, "
    "тому обхід сусідів має сталу вартість).")
r.p("**Cypher** — декларативна мова запитів Neo4j (основа стандарту ISO GQL). Шаблони графа "
    "записуються ASCII-art: `(a:Fault)-[:AFFECTS]->(c:Component)`. Основні конструкції: MATCH "
    "(зіставлення шаблону), WHERE (фільтри), OPTIONAL MATCH (аналог LEFT JOIN / OPTIONAL у SPARQL), "
    "RETURN з агрегуванням count, collect, avg (групування — неявне за неагрегованими полями), "
    "ORDER BY, LIMIT, WITH (конвеєр), параметри `$param` (план кешується, немає ін'єкцій). "
    "**Шляхи змінної довжини** `-[:SUBCLASS_OF*1..]->` дають транзитивне замикання, "
    "**shortestPath** — найкоротший шлях. Запис: CREATE (завжди створює) і **MERGE** (знаходить "
    "або створює — ідемпотентно, тому повторний імпорт не дає дублікатів).")
r.p("**Обмеження та індекси.** `CREATE CONSTRAINT ... REQUIRE n.iri IS UNIQUE` гарантує "
    "унікальність ключа (і автоматично створює RANGE-індекс), без нього MERGE за паралельного "
    "запису може створити дублікати. Індекси (RANGE, TEXT, FULLTEXT, VECTOR) прискорюють пошук "
    "стартових вузлів. План виконання показують EXPLAIN (без виконання) і **PROFILE** (з "
    "фактичними рядками та **db hits** — кількістю звернень до сховища).")
r.p("**Відображення OWL → LPG.** Класи можна подати мітками (швидко, але ієрархію втрачено) або "
    "вузлами :Class зі зв'язками :SUBCLASS_OF (ієрархія зберігається й доступна для запитів зі "
    "шляхами). Об'єктні властивості стають типами ребер, властивості даних — атрибутами. Плагін "
    "**neosemantics (n10s)** виконує таке відображення автоматично. Втрати: формальна семантика "
    "OWL (обмеження some/only, кардинальність, EquivalentTo, DisjointWith, характеристики "
    "властивостей) у Neo4j не інтерпретується — немає reasoner-а, тому виведені знання слід "
    "матеріалізувати до імпорту або обчислювати запитами.")

