def src(path, caption, a=1, b=None, name=None):
    """Скрін фрагмента файлу проєкту (не ноутбука)."""
    lines = Path(path).read_text(encoding="utf-8").splitlines()
    part = "\n".join(lines[a - 1:b])
    out = r.img / f"src_{Path(path).stem}_{a}.png"
    code_image(part, out, name or Path(path).name, a)
    r._picture(out, caption)


