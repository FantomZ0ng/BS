r.h1("Теоретичні відомості")
r.p("**RAG** (Retrieval-Augmented Generation, Lewis et al., 2020) — підхід, у якому мовна модель "
    "відповідає не лише з параметричної пам'яті, а на основі фрагментів, знайдених у зовнішньому "
    "корпусі. Конвеєр: документи → очищення → **chunking** (розбиття на фрагменти з метаданими) → "
    "**embeddings** (вектори фіксованої розмірності, близькі для схожих за змістом текстів) → "
    "векторний індекс; під час запиту: embedding запиту → пошук k найближчих фрагментів → промпт із "
    "фрагментами → LLM → відповідь із посиланнями на джерела. RAG зменшує галюцинації, дозволяє "
    "оновлювати знання без перенавчання і дає перевірювані цитати.")
r.p("**Chunking.** Фіксований розмір (напр. 400 токенів) з **перекриттям** (overlap 10–20 %) простий "
    "і рівномірний, але розрізає речення й списки; перекриття зменшує втрату контексту на межах. "
    "Структурне розбиття (за заголовками, абзацами) зберігає смислові одиниці, але дає фрагменти "
    "різної довжини. Важливо, щоб фрагмент уміщався у **вікно моделі embeddings** — довший текст "
    "обрізається (для paraphrase-multilingual-MiniLM — 128 токенів).")
r.p("**Векторний пошук.** Вектори нормалізують (‖v‖ = 1), тоді скалярний добуток дорівнює косинусній "
    "схожості, і індекс **IndexFlatIP** FAISS виконує точний пошук. Для великих корпусів застосовують "
    "наближені індекси: **IVF** (кластеризація k-means, пошук лише в nprobe найближчих кластерах) та "
    "**HNSW** (ієрархічний граф малого світу; висока швидкість і recall ціною пам'яті). Метадані "
    "(документ, розділ, сторінка, мова) дозволяють фільтрувати кандидатів.")
r.p("**BM25** — лексичне ранжування за частотою термінів з насиченням (k₁) і нормалізацією довжини (b) "
    "та IDF; добре знаходить точні збіги (коди помилок, команди), але не розуміє синонімів. **Dense**-пошук "
    "за embeddings знаходить перефразування, проте гірше працює з рідкісними токенами. **Гібрид RRF** "
    "(Reciprocal Rank Fusion) об'єднує списки без калібрування оцінок: score(d) = Σ 1/(60 + rank_i(d)). "
    "Якість пошуку вимірюють **recall@k** — часткою питань, для яких релевантний документ є серед перших k.")

