    "випадкова модель). **PR-крива** — precision від recall; її площа — average precision "
    "(AP), а базовий рівень дорівнює частці позитивного класу. За сильного дисбалансу "
    "ROC-крива виглядає оптимістично, бо FPR має великий знаменник (багато негативних), тоді "
    "як PR-крива чутлива до кількості хибних тривог відносно рідкісного класу — тому вона "
